// ass.js — Module 5: turn a caption document into a basic .ass subtitle file.
//
// Plain styling for now: readable white text, black outline, bottom-center.
// Sizes are derived from the video resolution so it looks right at any size.
// (Modules 6–7 will drive style/animation from template JSON instead.)

// ASS colours are &HAABBGGRR (alpha, blue, green, red), AA=00 is opaque.
const WHITE = "&H00FFFFFF";
const BLACK = "&H00000000";
const SHADOW = "&H64000000"; // ~40% transparent black drop shadow

// Pick a default font that can actually render the language's script.
function defaultFont(language) {
  switch ((language || "").toLowerCase()) {
    case "ur": return "Geeza Pro";            // Arabic/Urdu (ships with macOS)
    case "hi": return "Devanagari Sangam MN"; // Devanagari/Hindi (ships with macOS)
    default:   return "Arial";
  }
}

// seconds -> H:MM:SS.cc (centiseconds), with safe carry handling.
export function assTime(sec) {
  let cs = Math.max(0, Math.round(sec * 100));
  const h = Math.floor(cs / 360000); cs -= h * 360000;
  const m = Math.floor(cs / 6000);   cs -= m * 6000;
  const s = Math.floor(cs / 100);    cs -= s * 100;
  return `${h}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}.${String(cs).padStart(2, "0")}`;
}

// Make caption text safe for an ASS Dialogue field.
function escapeText(text) {
  return String(text)
    .replace(/\r?\n/g, "\\N") // real newlines -> ASS line break
    .replace(/\{/g, "(")       // braces start override blocks; neutralise them
    .replace(/\}/g, ")")
    .trim();
}

/**
 * Build a complete .ass file string from a caption doc + video dimensions.
 * @param {object} doc    caption document (Module 4 schema)
 * @param {{width:number, height:number}} dims
 */
export function buildAss(doc, dims) {
  const width = dims.width || 1280;
  const height = dims.height || 720;

  const fontSize = Math.min(120, Math.max(20, Math.round(height * 0.06)));
  const outline = Math.max(1, Math.round(height * 0.004));
  const shadow = Math.max(0, Math.round(height * 0.002));
  const marginV = Math.round(height * 0.05);
  const marginLR = Math.round(width * 0.04);
  const font = defaultFont(doc.source?.language);

  const header = [
    "[Script Info]",
    "; Generated by yourCaption",
    "ScriptType: v4.00+",
    `PlayResX: ${width}`,
    `PlayResY: ${height}`,
    "WrapStyle: 0",
    "ScaledBorderAndShadow: yes",
    "YCbCr Matrix: None",
    "",
    "[V4+ Styles]",
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
    // Alignment 2 = bottom-center. BorderStyle 1 = outline + drop shadow.
    `Style: Default,${font},${fontSize},${WHITE},&H000000FF,${BLACK},${SHADOW},0,0,0,0,100,100,0,0,1,${outline},${shadow},2,${marginLR},${marginLR},${marginV},1`,
    "",
    "[Events]",
    "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
  ];

  const events = (doc.lines || []).map((line) => {
    const start = assTime(line.start);
    const end = assTime(line.end);
    const text = escapeText(line.text);
    return `Dialogue: 0,${start},${end},Default,,0,0,0,,${text}`;
  });

  return header.concat(events).join("\n") + "\n";
}
