// ass.js — Module 5/6: turn a caption document into a .ass subtitle file,
// styled by a template (Module 6). Animation fields are declared by templates
// but implemented in Module 7; this module renders static styled lines.

import { resolveFontFamily, normalizeAnimation } from "./templates.js";

// Colour for inline override tags (\1c): ASS wants &HBBGGRR& (no alpha).
function hexToColorTag(hex) {
  const h = String(hex).replace(/^#/, "").trim().slice(0, 6);
  if (!/^[0-9a-fA-F]{6}$/.test(h)) return "&HFFFFFF&";
  return `&H${h.slice(4, 6)}${h.slice(2, 4)}${h.slice(0, 2)}&`.toUpperCase();
}

// Escape a single word for an ASS field (neutralise override braces).
function escapeWord(w) {
  return String(w).replace(/\{/g, "(").replace(/\}/g, ")");
}

// Build the inline override + text for the currently-active word.
function activeWordToken(word, anim, hlTag) {
  let ov = "";
  if (anim.highlight) ov += `\\1c${hlTag}`;
  if (anim.pop) ov += `\\fscx${anim.popScale}\\fscy${anim.popScale}\\t(0,${anim.popMs},\\fscx100\\fscy100)`;
  if (anim.fade) ov += `\\alpha&HFF&\\t(0,${anim.fadeMs},\\alpha&H00&)`;
  if (!ov) return escapeWord(word);
  return `{${ov}}${escapeWord(word)}{\\r}`; // \r resets to the Default style after the word
}

// Convert "#RRGGBB" or "#RRGGBBAA" (AA = opacity, FF = opaque) to ASS
// &HAABBGGRR (where ASS alpha is inverted: 00 = opaque, FF = transparent).
export function hexToAss(hex) {
  let h = String(hex).replace(/^#/, "").trim();
  let a = 255;
  if (h.length === 8) {
    a = parseInt(h.slice(6, 8), 16);
    h = h.slice(0, 6);
  }
  if (!/^[0-9a-fA-F]{6}$/.test(h)) {
    throw new Error(`Invalid colour '${hex}' (expected #RRGGBB or #RRGGBBAA)`);
  }
  const rr = h.slice(0, 2);
  const gg = h.slice(2, 4);
  const bb = h.slice(4, 6);
  const assA = (255 - a).toString(16).padStart(2, "0");
  return `&H${assA}${bb}${gg}${rr}`.toUpperCase();
}

// ASS alignment (numpad): bottom=2, middle=5, top=8 (all centered).
function alignToAss(align) {
  switch ((align || "bottom").toLowerCase()) {
    case "top": return 8;
    case "middle": return 5;
    default: return 2;
  }
}

// seconds -> H:MM:SS.cc (centiseconds), with safe carry handling.
export function assTime(sec) {
  let cs = Math.max(0, Math.round(sec * 100));
  const h = Math.floor(cs / 360000); cs -= h * 360000;
  const m = Math.floor(cs / 6000);   cs -= m * 6000;
  const s = Math.floor(cs / 100);    cs -= s * 100;
  return `${h}:${String(m).padStart(2, "0")}:${String(s).padStart(2, "0")}.${String(cs).padStart(2, "0")}`;
}

// Make caption text safe for an ASS Dialogue field.
function escapeText(text) {
  return String(text)
    .replace(/\r?\n/g, "\\N")
    .replace(/\{/g, "(")
    .replace(/\}/g, ")")
    .trim();
}

function pctOfHeight(height, pct, min = 0, max = Infinity) {
  return Math.min(max, Math.max(min, Math.round((height * pct) / 100)));
}

/**
 * Build a complete .ass file string from a caption doc, video dimensions,
 * and a resolved template.
 * @param {object} doc    caption document (Module 4 schema)
 * @param {{width:number, height:number}} dims
 * @param {object} template  resolved template (Module 6)
 */
export function buildAss(doc, dims, template) {
  const width = dims.width || 1280;
  const height = dims.height || 720;
  const language = doc.source?.language;

  const font = resolveFontFamily(template, language);
  const fontSize = pctOfHeight(height, template.font?.sizePct ?? 6, 12, 200);
  const outlineW = pctOfHeight(height, template.outline?.widthPct ?? 0.4, 0, 50);
  const shadowW = pctOfHeight(height, template.outline?.shadowPct ?? 0.15, 0, 50);
  const marginV = pctOfHeight(height, template.position?.marginVPct ?? 6, 0, height);
  const marginLR = pctOfHeight(width, template.position?.marginHPct ?? 4, 0, width);
  const alignment = alignToAss(template.position?.align);

  const primary = hexToAss(template.colors?.text ?? "#FFFFFF");
  const secondary = hexToAss(template.colors?.highlight ?? "#FFD400");
  const outlineColour = hexToAss(template.colors?.outline ?? "#000000");
  const backColour = hexToAss(template.colors?.shadow ?? "#000000A0");
  const bold = template.font?.bold ? -1 : 0;
  const italic = template.font?.italic ? -1 : 0;

  const header = [
    "[Script Info]",
    `; Generated by yourCaption — template: ${template.name}`,
    "ScriptType: v4.00+",
    `PlayResX: ${width}`,
    `PlayResY: ${height}`,
    "WrapStyle: 0",
    "ScaledBorderAndShadow: yes",
    "YCbCr Matrix: None",
    "",
    "[V4+ Styles]",
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
    `Style: Default,${font},${fontSize},${primary},${secondary},${outlineColour},${backColour},${bold},${italic},0,0,100,100,0,0,1,${outlineW},${shadowW},${alignment},${marginLR},${marginLR},${marginV},1`,
    "",
    "[Events]",
    "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
  ];

  const anim = normalizeAnimation(template.animation);
  const animated = anim.reveal || anim.highlight || anim.pop || anim.fade;
  const hlTag = hexToColorTag(template.colors?.highlight ?? "#FFD400");

  const events = [];
  for (const line of doc.lines || []) {
    const words = line.words || [];

    // Static path (animation "none"): one event per line — unchanged behaviour.
    if (!animated || words.length === 0) {
      events.push(`Dialogue: 0,${assTime(line.start)},${assTime(line.end)},Default,,0,0,0,,${escapeText(line.text)}`);
      continue;
    }

    // Animated path: one event per word's "active" window, redrawing the line.
    const n = words.length;
    for (let i = 0; i < n; i++) {
      // Reveal: words appear as spoken. Karaoke (no reveal): whole line shows
      // from line start, highlight sweeps across it.
      const start = anim.reveal ? words[i].start : (i === 0 ? Math.min(line.start, words[0].start) : words[i].start);
      const rawEnd = i < n - 1 ? words[i + 1].start : line.end;
      const end = Math.max(rawEnd, start + 0.05); // guard against zero/negative spans

      const visibleCount = anim.reveal ? i + 1 : n;
      const parts = [];
      for (let j = 0; j < visibleCount; j++) {
        parts.push(j === i ? activeWordToken(words[j].word, anim, hlTag) : escapeWord(words[j].word));
      }
      events.push(`Dialogue: 0,${assTime(start)},${assTime(end)},Default,,0,0,0,,${parts.join(" ")}`);
    }
  }

  return header.concat(events).join("\n") + "\n";
}
